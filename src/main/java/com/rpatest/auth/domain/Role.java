package com.rpatest.auth.domain;

/**
 * Единственная роль на пользователя (не M:N) — этого достаточно для трёх уровней доступа, не
 * усложняем отдельной таблицей ролей/прав без реальной необходимости в нескольких ролях на
 * пользователя. Иерархия ADMIN {@literal >} OPERATOR {@literal >} VIEWER задаётся явно в матрице
 * доступа {@code SecurityConfig} (см. ADR 0003), не через Spring Security {@code RoleHierarchy}.
 */
public enum Role {
    /** Всё, что может OPERATOR, плюс управление пользователями (`/api/v1/admin/**`) и удаление сценариев. */
    ADMIN,
    /** CRUD сценариев (кроме удаления), запуск/остановка прогонов, cleanup. Чтение — как у VIEWER. */
    OPERATOR,
    /** Только чтение: список/просмотр сценариев, статус прогонов, элементы очереди, доступность роботов. */
    VIEWER
}
